    static class StubWalletDAO extends WalletDAO {
        private final ConcurrentHashMap<Long, Wallet> map = new ConcurrentHashMap<>();
        private final BigDecimal initialBalance;

        StubWalletDAO() {
            this(new BigDecimal("100000.00"));
        }

        StubWalletDAO(BigDecimal initialBalance) {
            this.initialBalance = initialBalance;
            Wallet w1 = new Wallet();
            w1.setUserId(1L);
            w1.setBalance(initialBalance);
            w1.setReserved(BigDecimal.ZERO);
            map.put(1L, w1);
            Wallet w2 = new Wallet();
            w2.setUserId(2L);
            w2.setBalance(initialBalance);
            w2.setReserved(BigDecimal.ZERO);
            map.put(2L, w2);
        }

        @Override
        public Wallet findByUserId(Long userId) {
            return map.get(userId);
        }

        @Override
        public Wallet findOrCreateByUserId(Long userId) {
            return map.computeIfAbsent(userId, id -> {
                Wallet w = new Wallet();
                w.setUserId(id);
                w.setBalance(initialBalance);
                w.setReserved(BigDecimal.ZERO);
                return w;
            });
        }

        @Override
        public void updateBalances(Long userId, BigDecimal balance, BigDecimal reserved) {
            Wallet w = findOrCreateByUserId(userId);
            w.setBalance(balance);
            w.setReserved(reserved);
            map.put(userId, w);
        }
    }

