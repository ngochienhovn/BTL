    @Test
    void concurrency_fifty_threads_highest_bid_wins() throws Exception {
        Auction auction = createRunningAuction(51L, 100.0, 3600);

        int threadCount = 50;
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);
        CountDownLatch latch = new CountDownLatch(threadCount);

        for (int i = 0; i < threadCount; i++) {
            double bidAmount = 150.0 + i * 10;
            executor.submit(() -> {
                try {
                    auctionService.placeBid(51L, "bidder1@test.com", bidAmount);
                } finally {
                    latch.countDown();
                }
            });
        }

        latch.await();
        executor.shutdown();

        assertEquals(640.0, auction.getCurrentBid().doubleValue(), 1.0);
        WalletService ws = WalletService.getInstance();
        Wallet w = ws.getWallet(1L);
        assertTrue(w.getReserved().compareTo(java.math.BigDecimal.ZERO) >= 0);
    }

    @Test
    void concurrentBids_no_lost_update() throws Exception {
        Auction auction = createRunningAuction(6L, 100.0, 3600);

        int threadCount = 10;
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);
        CountDownLatch latch = new CountDownLatch(threadCount);
        AtomicInteger successCount = new AtomicInteger(0);

        for (int i = 0; i < threadCount; i++) {
            final double bidAmount = 200.0 + i * 10;
            executor.submit(() -> {
                try {
                    BidResult result = auctionService.placeBid(6L, "bidder1@test.com", bidAmount);
                    if (result.code() == BidResultCode.OK) {
                        successCount.incrementAndGet();
                    }
                } finally {
                    latch.countDown();
                }
            });
        }

        latch.await();
        executor.shutdown();

        // At least some bids should succeed; current bid should be the highest valid bid
        assertTrue(successCount.get() >= 1);
        assertTrue(auction.getCurrentBid().doubleValue() >= 200.0);
        // The bid list should be consistent (no negative bids, no duplicates of same amount from race)
        assertFalse(auction.getBids().isEmpty());
    }

    @Test
    void placeBid_rollsBack_onDatabaseException() throws Exception {
        Auction auction = createRunningAuction(88L, 100.0, 3600);

        Field bidDAOField = AuctionService.class.getDeclaredField("bidDAO");
        bidDAOField.setAccessible(true);
        bidDAOField.set(auctionService, new TestBidDAO() {
            @Override
            public Long insert(com.ltnc.auction.server.model.BidTransaction bid) {
                try {
                    WalletService ws = WalletService.getInstance();
                    Field walletDaoField = WalletService.class.getDeclaredField("walletDAO");
                    walletDaoField.setAccessible(true);
                    Object stubWalletDAO = walletDaoField.get(ws);
                    ((StubWalletDAO) stubWalletDAO).updateBalances(1L, new BigDecimal("100000.00"), BigDecimal.ZERO);
                } catch (Exception ignored) {}
                throw new RuntimeException("Simulated Database Failure");
            }
        });

        WalletService ws = WalletService.getInstance();
        Wallet initialWallet = ws.getWallet(1L);
        BigDecimal initialReserved = initialWallet.getReserved();
        BigDecimal initialBalance = initialWallet.getBalance();

        assertThrows(RuntimeException.class, () -> {
            auctionService.placeBid(88L, "bidder1@test.com", 150.0);
        });

        assertEquals(100.0, auction.getCurrentBid().doubleValue(), 0.01);
        assertNull(auction.getHighestBidderId());

        Wallet finalWallet = ws.getWallet(1L);
        assertEquals(initialReserved, finalWallet.getReserved());
        assertEquals(initialBalance, finalWallet.getBalance());
    }

