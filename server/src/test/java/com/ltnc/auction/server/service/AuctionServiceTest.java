    @Test
    void registerAutoBid_validation() throws Exception {
        Auction auction = createRunningAuction(70L, 100.0, 3600);

        // 1. Valid registration
        boolean ok1 = auctionService.registerAutoBid(70L, "bidder1@test.com", 150.0, 10.0);
        assertTrue(ok1);

        // 2. Max bid too low (less than or equal to current price of 100)
        boolean ok2 = auctionService.registerAutoBid(70L, "bidder1@test.com", 100.0, 10.0);
        assertFalse(ok2);
        boolean ok3 = auctionService.registerAutoBid(70L, "bidder1@test.com", 90.0, 10.0);
        assertFalse(ok3);

        // 3. Step/increment <= 0
        boolean ok4 = auctionService.registerAutoBid(70L, "bidder1@test.com", 150.0, 0.0);
        assertFalse(ok4);
        boolean ok5 = auctionService.registerAutoBid(70L, "bidder1@test.com", 150.0, -5.0);
        assertFalse(ok5);
    }

