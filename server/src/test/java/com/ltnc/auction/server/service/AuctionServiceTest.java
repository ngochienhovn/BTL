    static class TestAuctionDAO extends AuctionDAO {
        private final ConcurrentHashMap<Long, Auction> store = new ConcurrentHashMap<>();
        private long nextId = 100;

        @Override
        public Long insert(Auction auction) {
            long id = nextId++;
            auction.setId(id);
            store.put(id, auction);
            return id;
        }

        @Override
        public boolean updateCurrentBid(Long auctionId, java.math.BigDecimal newBid, Long highestBidderId) {
            Auction a = store.get(auctionId);
            if (a != null) {
                a.setCurrentBid(newBid);
                a.setHighestBidderId(highestBidderId);
            }
            return true;
        }

        @Override
        public boolean updateStatus(Long auctionId, String status, String winnerEmail) {
            Auction a = store.get(auctionId);
            if (a != null) {
                a.setStatus(status);
                a.setWinnerEmail(winnerEmail);
            }
            return true;
        }

        @Override
        public boolean updateEndTime(Long auctionId, LocalDateTime newEndTime) {
            Auction a = store.get(auctionId);
            if (a != null) {
                a.setEndTime(newEndTime);
            }
            return true;
        }

        @Override
        public Auction findById(Long id) {
            return store.get(id);
        }

        @Override
        public List<Auction> findAll() {
            return new ArrayList<>(store.values());
        }

        @Override
        public List<Auction> findByStatus(String status) {
            return store.values().stream()
                    .filter(a -> status.equals(a.getStatus()))
                    .collect(java.util.stream.Collectors.toList());
        }
    }

